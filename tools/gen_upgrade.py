"""
Writes database/upgrade-from-v1.3.sql from database/create-database.sql.

create-database.sql builds a new database (and drops an existing one). An office that already
runs v1.3 needs the v1.3.1 changes without losing its data. This script takes the new objects
straight from create-database.sql, so the two cannot drift apart:
  * column changes and the fee snapshot columns (with a backfill that keeps old totals),
  * every constraint, index and column from the "Links the EF model does not navigate" block,
    each added only if it does not exist yet,
  * every trigger and procedure, as CREATE OR ALTER.
The whole upgrade runs in one transaction: if anything fails, nothing changes.

Usage: python tools/gen_upgrade.py database/create-database.sql database/upgrade-from-v1.3.sql
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
sql = open(src, encoding='utf-8-sig').read()

# The constraints added in v1.3.1 sit between this comment and the next GO.
start = sql.index('-- Links the EF model does not navigate')
extras = sql[start:sql.index('\nGO', start)]

guarded = []
for line in extras.splitlines():
    line = line.rstrip()
    if not line or line.startswith('--'):
        guarded.append(line)
        continue
    m = re.match(r"ALTER TABLE \[dbo\]\.\[(\w+)\] ADD (?:CONSTRAINT \[(\w+)\]|\[(\w+)\] .*CONSTRAINT \[(\w+)\])", line)
    if m and m.group(2):            # ADD CONSTRAINT [name] ...
        guarded.append("IF OBJECT_ID(N'dbo.%s') IS NULL\n    %s" % (m.group(2), line))
    elif m and m.group(3):          # ADD [column] ... CONSTRAINT [default]
        guarded.append("IF COL_LENGTH(N'dbo.%s', N'%s') IS NULL\n    %s" % (m.group(1), m.group(3), line))
    else:
        m = re.match(r"CREATE UNIQUE INDEX \[(\w+)\] ON \[dbo\]\.\[(\w+)\]", line)
        if not m:
            raise SystemExit('unexpected line in the constraints block: ' + line)
        guarded.append("IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'%s' AND object_id = OBJECT_ID(N'dbo.%s'))\n    %s"
                       % (m.group(1), m.group(2), line))

# Triggers and procedures: each is a batch that starts with CREATE TRIGGER / CREATE PROCEDURE.
modules = []
for m in re.finditer(r'^(?:--[^\n]*\n)*CREATE (TRIGGER|PROCEDURE) .*?^GO\n', sql, re.S | re.M):
    modules.append(re.sub(r'^CREATE (TRIGGER|PROCEDURE)', r'CREATE OR ALTER \1', m.group(0), count=1, flags=re.M))
if len(modules) < 5:
    raise SystemExit('expected the triggers and procedures in ' + src)

text = '''/*
    QUEDIN - upgrade an existing v1.3 or v1.3.1 database to the current version (keeps all data).
    Generated by tools/gen_upgrade.py from create-database.sql - do not edit by hand.

    Run once:   sqlcmd -S "(localdb)\\MSSQLLocalDB" -b -i database\\upgrade-from-v1.3.sql
    Then run security.sql again (it adds the permissions for the new procedures).
    Everything runs in one transaction: if any step fails, the database is left as it was.
    Running it again on an upgraded database changes nothing.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO
USE [QuedinDB];
GO
BEGIN TRANSACTION;
GO

-- ---------------------------------------------------------- columns
-- Opposing party / lawyer ids now match Customers.CustomerId (needed for the new foreign keys).
IF COL_LENGTH(N'dbo.Cases', N'OpposingPartyId') <> 40
    ALTER TABLE [dbo].[Cases] ALTER COLUMN [OpposingPartyId] nvarchar(20) NOT NULL;
IF COL_LENGTH(N'dbo.Cases', N'OpposingLawyerId') <> 40
    ALTER TABLE [dbo].[Cases] ALTER COLUMN [OpposingLawyerId] nvarchar(20) NOT NULL;
-- "****1234" is 8 characters.
IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID(N'dbo.Payments') AND name = N'CardLast4' AND system_type_id = TYPE_ID(N'nchar'))
BEGIN
    UPDATE [dbo].[Payments] SET [CardLast4] = RTRIM([CardLast4]) WHERE [CardLast4] IS NOT NULL;
    ALTER TABLE [dbo].[Payments] ALTER COLUMN [CardLast4] nvarchar(8) NULL;
END
-- Each case keeps the fees of its case type from when it was opened.
IF COL_LENGTH(N'dbo.Cases', N'MinimumFee') IS NULL
    ALTER TABLE [dbo].[Cases] ADD [MinimumFee] money NULL;
IF COL_LENGTH(N'dbo.Cases', N'CourtFee') IS NULL
    ALTER TABLE [dbo].[Cases] ADD [CourtFee] money NULL;
GO
-- Existing cases were opened before the minimum fee existed: they keep their old totals.
UPDATE c SET [CourtFee] = ISNULL(t.[CourtFee], 0), [MinimumFee] = 0
FROM [dbo].[Cases] c JOIN [dbo].[CaseTypes] t ON t.[CaseTypeId] = c.[CaseTypeId]
WHERE c.[CourtFee] IS NULL;
GO

-- ---------------------------------------------------------- constraints (only those still missing)
''' + '\n'.join(guarded) + '''
GO

-- ---------------------------------------------------------- triggers and procedures
''' + '\n'.join(modules) + '''
COMMIT TRANSACTION;
GO
PRINT N'QuedinDB was upgraded. Now run security.sql again.';
GO
'''
open(out, 'w', encoding='utf-8-sig').write(text)
print('ok', len(guarded), 'constraint lines,', len(modules), 'modules')
